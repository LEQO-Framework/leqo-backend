QUBIT_REGISTER = "q"


class UnsupportedCircuitError(Exception):
    """
    The generated OpenQASM 3 program uses a construct that has no OpenQASM 2 equivalent here.
    """


@dataclass(frozen=True)
class GeneratedCircuit:
    """
    OpenQASM 2 circuit of one candidate for a QUBO.
    """

    candidate: Candidate
    qasm: str
    width: int


def _qaoa_node(qubo: QUBOProblem, layers: int) -> QAOANode:
    """
    QAOA node whose cost layer is the Ising Hamiltonian of the QUBO.

    The "QUBO" cost layer of :class:`~app.enricher.qaoa.QAOAEnricherStrategy` maps
    ``x = (1 - z) / 2`` and has one weighted ZZ interaction per coupling
    and one RZ gate per non-zero local field.
    The angles are untrained, which is enough for the gate structure the NISQ Analyzer needs.
    """

    qubit_of = {variable: q for q, variable in enumerate(qubo.coupled_variables)}
    edges = [[qubit_of[i], qubit_of[j], w] for (i, j), w in qubo.couplings.items()]
    linear = [qubo.matrix[i][i] for i in qubo.coupled_variables]
    return QAOANode(
        id="qubo-qaoa",
        p=layers,
        problem="QUBO",
        optimizer="COBYLA",
        edges=str(edges),
        linear=str(linear),
        outputIdentifier=QUBIT_REGISTER,
    )


def _vqe_node(qubo: QUBOProblem, layers: int) -> VQENode:
    """
    VQE node with the hardware-efficient ansatz on one qubit per coupled variable.
    """

    return VQENode(
        id="qubo-vqe",
        numQubits=len(qubo.coupled_variables),
        ansatz="HardwareEfficient",
        layers=layers,
        parameters="",
        observable="",
        optimizer="COBYLA",
        outputIdentifier=QUBIT_REGISTER,
    )


@dataclass(frozen=True)
class AlgorithmImplementation:
    """
    Builds the frontend node of an algorithm for a QUBO and names the strategy that enriches it.
    """

    build_node: Callable[[QUBOProblem, int], FrontendNode]
    strategy: EnricherStrategy


# All algorithms of this project that can be applied to an arbitrary QUBO.
ALGORITHM_IMPLEMENTATIONS: dict[QuantumAlgorithm, AlgorithmImplementation] = {
    QuantumAlgorithm.QAOA: AlgorithmImplementation(_qaoa_node, QAOAEnricherStrategy()),
    QuantumAlgorithm.VQE: AlgorithmImplementation(_vqe_node, VQEEnricherStrategy()),
}


def _float_value(expression: Expression) -> float:
    match expression:
        case FloatLiteral(value=value) | IntegerLiteral(value=value):
            return float(value)
        case UnaryExpression(expression=inner) if expression.op == UnaryOperator["-"]:
            return -_float_value(inner)
    msg = f"Unsupported gate argument {type(expression).__name__}."
    raise UnsupportedCircuitError(msg)


def program_to_qasm2(program: Program) -> str:
    """
    Convert a gate-level OpenQASM 3 program to OpenQASM 2 and measure all qubits.

    Supports the subset generated by the algorithm enrichers: qubit declarations,
    unmodified standard gates and the leqo output alias.
    """

    gates = get_standard_gate_name_mapping()
    registers: dict[str, QuantumRegister] = {}
    circuit = QuantumCircuit()

    def qubit(target: object) -> Qubit:
        match target:
            case IndexedIdentifier(
                name=Identifier(name=name), indices=[[IntegerLiteral(value=index)]]
            ) if name in registers:
                return registers[name][index]
        msg = f"Unsupported qubit operand {target}."
        raise UnsupportedCircuitError(msg)

    for statement in program.statements:
        match statement:
            case Include() | AliasStatement():
                continue
            case QubitDeclaration(
                qubit=Identifier(name=name), size=IntegerLiteral(value=size)
            ):
                registers[name] = QuantumRegister(size, name)
                circuit.add_register(registers[name])
            case QuantumGate(modifiers=[], name=Identifier(name=name)) if name in gates:
                template = gates[name]
                arguments = [_float_value(a) for a in statement.arguments]
                if len(arguments) != len(template.params):
                    msg = f"Gate {name} expects {len(template.params)} arguments."
                    raise UnsupportedCircuitError(msg)
                circuit.append(
                    type(template)(*arguments), [qubit(q) for q in statement.qubits]
                )
            case _:
                msg = f"Unsupported statement {type(statement).__name__}."
                raise UnsupportedCircuitError(msg)

    circuit.measure_all()
    qasm: str = qasm2.dumps(circuit)
    return qasm


DEFAULT_CANDIDATES = (
    Candidate(algorithm=QuantumAlgorithm.QAOA, layers=1),
    Candidate(algorithm=QuantumAlgorithm.VQE, layers=1),
)


class QuboCircuitService:
    """
    Generates the circuits of all candidates and analyzes them with the NISQ Analyzer.
    """

    def __init__(
        self,
        nisq_client: NisqAnalyzerClient,
        candidates: Sequence[Candidate] = DEFAULT_CANDIDATES,
    ):
        """
        :param nisq_client: Client of the NISQ Analyzer.
        :param candidates: Algorithms and circuit depths to choose from.
        """

        if not candidates:
            msg = "At least one candidate is needed."
            raise ValueError(msg)
        self.nisq_client = nisq_client
        self.candidates = list(candidates)

    async def generate(
        self, qubo: QUBOProblem, candidate: Candidate
    ) -> GeneratedCircuit:
        """
        Generate the OpenQASM 2 circuit of one candidate with its enricher strategy.
        """

        implementation = ALGORITHM_IMPLEMENTATIONS[candidate.algorithm]
        node = implementation.build_node(qubo, candidate.layers)
        results = list(await implementation.strategy.enrich(node, None))
        if not results:
            msg = f"{type(implementation.strategy).__name__} did not enrich {node.id}."
            raise UnsupportedCircuitError(msg)

        enriched = results[0].enriched_node
        if not isinstance(enriched, ParsedImplementationNode):
            msg = f"Expected a parsed implementation for {node.id}."
            raise UnsupportedCircuitError(msg)
        program = enriched.implementation

        width = results[0].meta_data.width
        return GeneratedCircuit(
            candidate=candidate,
            qasm=program_to_qasm2(program),
            width=width if width is not None else len(qubo.coupled_variables),
        )

    async def analyze(self, qubo: QUBOProblem) -> list[CandidateEvaluation]:
        """
        Generate the circuits of all candidates and select a QPU for each with the NISQ Analyzer.
        """

        circuits = [await self.generate(qubo, c) for c in self.candidates]
        return list(await asyncio.gather(*(self._evaluate(c) for c in circuits)))

    async def _evaluate(self, circuit: GeneratedCircuit) -> CandidateEvaluation:
        candidate = circuit.candidate
        evaluation = CandidateEvaluation(
            algorithm=candidate.algorithm,
            layers=candidate.layers,
            qasm=circuit.qasm,
            width=circuit.width,
        )
        try:
            evaluation.qpu_selection = await self.nisq_client.select_qpu(
                circuit.qasm, f"qubo-{candidate.algorithm.lower()}-{candidate.layers}"
            )
            evaluation.nisq_reachable = True
        except NoSuitableQpuError as ex:
            evaluation.nisq_reachable = True
            evaluation.nisq_error = str(ex)
        except NisqAnalyzerError as ex:
            evaluation.nisq_error = str(ex)
        return evaluation
